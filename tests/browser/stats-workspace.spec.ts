import {test,expect} from '@playwright/test'
import {mkdtempSync,existsSync,readFileSync} from 'node:fs'
import {tmpdir} from 'node:os'
import path from 'node:path'

test('independent workspace imports, analyses, freezes, exports and reopens',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/?integration=1')
 await page.locator('.app-shell:visible').getByRole('button',{name:'统计与绘图',exact:true}).click()
 const app=page.locator('.stats-shell')
 await app.getByRole('button',{name:'新建统计项目',exact:true}).first().click()
 await app.getByLabel('统计项目名称').fill('统计端到端测试')
 await app.getByRole('button',{name:'导入 / 粘贴',exact:true}).click()
 await app.getByLabel('粘贴统计数据').fill('Control\tTreatment A\tTreatment B\n1\t2\t4\n2\t3\t5\n3\t4\t6')
 await app.getByRole('button',{name:'预览粘贴数据',exact:true}).click()
 await expect(app.getByText('3 行 / Control、Treatment A、Treatment B')).toBeVisible()
 await app.getByRole('button',{name:'添加数据表',exact:true}).click()
 await app.getByRole('button',{name:'设置统计分析',exact:true}).click()
 await app.getByLabel('统计方法',{exact:true}).selectOption('anova')
 await app.getByLabel('统计比较范围').selectOption('all')
 await app.getByLabel('确认独立单位').check()
 await app.getByRole('button',{name:'运行分析',exact:true}).click()
 await expect(app.getByText('总体检验：F = 7，P = 0.027')).toBeVisible()
 await app.getByRole('button',{name:'查看图形',exact:true}).click()
 await app.getByLabel('统计标注').selectOption('p')
 await app.getByLabel('宽度 mm').fill('60')
 await app.getByLabel('高度 mm').fill('50')
 await expect(app.getByRole('img',{name:'统计图预览'})).toBeVisible()
 await app.getByRole('button',{name:'保存图形快照',exact:true}).click()
 await expect(app.getByRole('status').filter({hasText:'已保存图形快照'})).toBeVisible()
 const destination=path.join(mkdtempSync(path.join(tmpdir(),'titan-stats-e2e-')),'export')
 await app.getByRole('button',{name:'导出',exact:true}).click()
 await app.getByLabel('统计文件路径').fill(destination)
 await app.getByRole('button',{name:'确认',exact:true}).click()
 await expect(app.getByRole('status').filter({hasText:'已保存至'})).toBeVisible({timeout:20000})
 expect(existsSync(path.join(destination,'plot.pdf'))).toBe(true)
 expect(readFileSync(path.join(destination,'plot.svg'),'utf8')).toContain('<text')
 await app.getByRole('button',{name:'保存',exact:true}).click()
 await expect(app.getByText('已保存',{exact:true})).toBeVisible()
 await page.screenshot({path:'artifacts/stats-graph.png',fullPage:true})
 await page.reload()
 await page.locator('.app-shell:visible').getByRole('button',{name:'统计与绘图',exact:true}).click()
 await app.getByRole('button',{name:'统计端到端测试',exact:true}).click()
 await expect(app.getByLabel('统计项目名称')).toHaveValue('统计端到端测试')
 await app.getByRole('button',{name:'导入数据 · 图 1',exact:true}).click()
 await expect(app.getByText(/正在查看冻结图形/)).toBeVisible()
 await expect(app.getByRole('img',{name:'统计图预览'})).toBeVisible()
 expect(errors).toEqual([])
})

test('WB transfers source-linked independent units and IF remains accessible',async({page})=>{
 await page.goto('/?integration=1')
 const wb=page.locator('.app-shell:visible')
 await wb.getByRole('button',{name:'体验合成示例',exact:true}).click()
 await wb.getByRole('button',{name:'定量结果',exact:true}).click()
 await expect(wb.getByRole('button',{name:'发送到统计与绘图'})).toBeEnabled()
 await wb.getByRole('button',{name:'发送到统计与绘图'}).click()
 const app=page.locator('.stats-shell')
 await expect(app.getByText(/WB 来源：/)).toBeVisible()
 await expect(app.getByLabel('数值 1 1')).toBeDisabled()
 await app.getByRole('button',{name:'免疫荧光',exact:true}).click()
 await expect(page.locator('.if-shell')).toBeVisible()
 await page.locator('.if-shell').getByRole('button',{name:'统计与绘图',exact:true}).click()
 await expect(app).toBeVisible()
})
