import {createAnalysis} from './library-actions'
import {test,expect} from '@playwright/test'
import {mkdtempSync,existsSync,readFileSync} from 'node:fs'
import {tmpdir} from 'node:os'
import path from 'node:path'

test('independent workspace imports, analyses, freezes, exports and reopens',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/?integration=1')
 await page.locator('.app-shell:visible').getByRole('button',{name:'统计与绘图',exact:true}).click()
 const app=page.locator('.stats-shell')
 await createAnalysis(page,'stats',true,'统计端到端测试')
 await app.getByRole('button',{name:'导入 / 粘贴',exact:true}).click()
 await app.getByLabel('粘贴统计数据').fill('Control\tTreatment A\tTreatment B\n1\t2\t4\n2\t3\t5\n3\t4\t6')
 await app.getByRole('button',{name:'预览粘贴数据',exact:true}).click()
 await expect(app.getByText('3 行 / Control、Treatment A、Treatment B')).toBeVisible()
 await app.getByRole('button',{name:'添加数据表',exact:true}).click()
 await app.getByRole('button',{name:'设置统计分析',exact:true}).click()
 await app.getByLabel('统计方法',{exact:true}).selectOption('anova')
 await app.getByLabel('统计比较范围').selectOption('all')
 await app.getByLabel('确认独立单位').check()
 await app.getByRole('button',{name:'运行分析',exact:true}).click()
 await expect(app.getByText('总体检验：F = 7，P = 0.027')).toBeVisible()
 await app.getByRole('button',{name:'查看图形',exact:true}).click()
 await app.getByLabel('统计标注').selectOption('p')
 await app.getByLabel('宽度 mm').fill('60')
 await app.getByLabel('高度 mm').fill('50')
 await expect(app.getByRole('img',{name:'统计图预览'})).toBeVisible()
 await app.getByRole('button',{name:'保存图形快照',exact:true}).click()
 await expect(app.getByRole('status').filter({hasText:'已保存图形快照'})).toBeVisible()
 const destination=path.join(mkdtempSync(path.join(tmpdir(),'titan-stats-e2e-')),'export')
 await app.getByRole('button',{name:'导出',exact:true}).click()
 await app.getByLabel('统计文件路径').fill(destination)
 await app.getByRole('button',{name:'确认',exact:true}).click()
 await expect(app.getByRole('status').filter({hasText:'已保存至'})).toBeVisible({timeout:20000})
 expect(existsSync(path.join(destination,'plot.pdf'))).toBe(true)
 expect(readFileSync(path.join(destination,'plot.svg'),'utf8')).toContain('<text')
 await app.getByRole('button',{name:'保存',exact:true}).click()
 await expect(app.getByText('已保存',{exact:true})).toBeVisible()
 await page.screenshot({path:'artifacts/stats-graph.png',fullPage:true})
 const original=JSON.parse(readFileSync(path.join(destination,'analysis.json'),'utf8'))
 await app.getByRole('button',{name:'分析结果 · 1',exact:true}).click()
 await app.getByText('分析历史（1）',{exact:true}).click()
 await app.getByRole('button',{name:/ · anova$/}).click()
 const historical=path.join(path.dirname(destination),'historical')
 await app.getByRole('button',{name:'导出',exact:true}).click()
 await app.getByLabel('统计文件路径').fill(historical)
 await app.getByRole('button',{name:'确认',exact:true}).click()
 await expect(app.getByRole('status').filter({hasText:'已保存至'})).toBeVisible({timeout:20000})
 const archived=JSON.parse(readFileSync(path.join(historical,'analysis.json'),'utf8'))
 expect(archived.run.id).toBe(original.run.id)
 expect(archived.style.width_mm).toBe(80)
 await page.reload()
 await page.locator('.app-shell:visible').getByRole('button',{name:'统计与绘图',exact:true}).click()
 await app.getByRole('button',{name:'打开分析 统计端到端测试',exact:true}).click()
 await expect(app.getByLabel('统计项目名称')).toHaveValue('统计端到端测试')
 await app.getByRole('button',{name:'打开组图 导入数据 · 图 1',exact:true}).click()
 await expect(app.getByText(/正在查看冻结图形/)).toBeVisible()
 await expect(app.getByRole('img',{name:'统计图预览'})).toBeVisible()
 expect(errors).toEqual([])
})

test('saved WB results enter the selected project and return to their source',async({page})=>{
 await page.goto('/?integration=1')
 const rpc=async(command:string,payload:object={})=>{
  const response=await page.request.post('/test-engine',{data:{command,payload}})
  const result=await response.json();expect(result.ok,result.error).toBe(true);return result.data
 }
 const group=await rpc('library_create_collection',{name:'统计关联合成课题 '+Date.now()})
 const created=await rpc('library_create',{name:'WB统计关联合成验证 '+Date.now(),collection_id:group.id})
 const demo=await rpc('demo')
 Object.assign(demo,{id:created.project.id,name:created.project.name,project_path:created.project.project_path,saved_revision:0})
 await rpc('save_project',{project:demo,path:demo.project_path,expected_revision:0})
 await page.reload()
 const other=await rpc('library_create_collection',{name:'另一个项目 '+Date.now()})
 const unrelatedName='其他项目里的统计 '+Date.now()
 await createAnalysis(page,'stats',true,unrelatedName)
 const unrelated=(await rpc('library_workspace')).entries.find((entry:any)=>entry.name===unrelatedName)
 await rpc('library_assign',{entry_id:unrelated.entry_id,collection_id:other.id})
 const wb=page.locator('.app-shell:visible')
 await wb.getByRole('button',{name:'展开项目 '+group.name,exact:true}).click()
 await wb.getByRole('button',{name:'打开分析 '+demo.name,exact:true}).click()
 await wb.getByRole('button',{name:'开始定量',exact:true}).click()
 await wb.getByRole('button',{name:'发送到统计与绘图'}).click()
 const selection=page.getByRole('dialog',{name:'从项目读取结果'})
 await selection.getByRole('button',{name:'取消',exact:true}).click()
 await expect(wb.getByLabel('实验名称',{exact:true})).toHaveValue(demo.name)
 await wb.getByRole('button',{name:'发送到统计与绘图'}).click()
 const app=page.locator('.stats-shell')
 await selection.getByRole('checkbox',{name:/选择指标/}).first().check()
 await expect(selection.getByLabel('结果读取目标')).toHaveValue('new')
 await expect(selection.getByLabel('归属项目')).toHaveValue(group.id)
 await selection.getByLabel('确认来源统计单位').check()
 await selection.getByRole('button',{name:'读取所选结果'}).click()
 await expect(app.getByText(/WB 来源：/)).toBeVisible()
 await expect(app.getByLabel('数值 1 1')).toBeDisabled()
 const library=await rpc('library_workspace')
 const stats=library.entries.find((entry:any)=>entry.name===demo.name+' · 统计')
 expect(stats?.collection_id).toBe(group.id)
 const previous=await rpc('stats_open',{path:unrelated.path})
 expect(previous.datasets).toHaveLength(1)
 expect(previous.datasets[0].source).toBeNull()
 await app.getByRole('button',{name:'返回 WB',exact:true}).click()
 await expect(page.locator('.app-shell:visible').getByLabel('实验名称')).toHaveValue(demo.name)
 await page.locator('.app-shell:visible').getByRole('button',{name:'免疫荧光',exact:true}).click()
 await expect(page.locator('.if-shell')).toBeVisible()
})
