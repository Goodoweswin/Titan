test('retained rename results match recomputation and remain exportable by the real engine',async({page},testInfo)=>{
 await page.goto('/?integration=1')
 const output=await page.evaluate(async destination=>{
  const {editProject,retainResult}=await import('/src/state.ts')
  async function engine(command:string,payload={}){
   const response=await fetch('/test-engine',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({command,payload})})
   const envelope=await response.json();if(!envelope.ok)throw new Error(envelope.error);return envelope.data
  }
  const original=await engine('demo'),result=await engine('analyze',{project:original})
  const project=editProject(original,(p:any)=>{p.name='改名后导出'})
  const retained=retainResult(original,project,result),recomputed=await engine('analyze',{project})
  const manifest=await engine('export',{project,result:retained,destination})
  return {retained,recomputed,revision:project.revision,exportRevision:manifest.revision}
 },testInfo.outputPath('renamed-export'))
 expect(output.retained).toEqual(output.recomputed)
 expect(output.exportRevision).toBe(output.revision)
})

