test('tutorial saves, reopens and exports PNG PDF SVG with synthetic provenance',async({page})=>{
 const root=mkdtempSync(path.join(tmpdir(),'titan-case-browser-'))
 try{
  const projectPath=path.join(root,'case.titanwb'),destination=path.join(root,'figure')
  await page.goto('/?integration=1')
  await page.getByRole('button',{name:'教程',exact:true}).click()
  await page.getByRole('button',{name:'退出引导',exact:true}).click()
  const name='Tutorial persistence '+Date.now();await page.getByLabel('实验名称',{exact:true}).fill(name)
  await expect(page.getByLabel('泳道分析画布')).toBeVisible()
  await page.evaluate((dest:string)=>{(window as any).__TAURI_INTERNALS__={invoke:async(c:string)=>{if(c==='plugin:dialog|save')return dest;throw Error(c)}}},projectPath)
  await page.getByRole('button',{name:'保存实验',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'实验已保存'})).toBeVisible()
  await page.reload()
  await page.getByRole('button',{name:'打开分析 '+name,exact:true}).click()
  await expect(page.getByText('教程已暂停',{exact:false})).toBeVisible()
  await page.getByRole('button',{name:'WB 组图',exact:true}).click()
  await page.getByRole('button',{name:'新建组图',exact:true}).first().click()
  await page.getByRole('button',{name:'确认本行裁剪',exact:true}).click()
  await expect(page.getByRole('group',{name:'WB 组图预览',exact:true})).toBeVisible()
  await page.evaluate((dest:string)=>{(window as any).__TAURI_INTERNALS__={invoke:async(c:string)=>{if(c==='plugin:dialog|save')return dest;throw Error(c)}}},destination)
  await page.getByRole('button',{name:'导出组图',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'已导出 PNG、PDF'})).toBeVisible()
  expect(readFileSync(path.join(destination,'figure.pdf')).subarray(0,5).toString()).toBe('%PDF-')
  expect(readFileSync(path.join(destination,'figure.svg'),'utf8')).toContain('合成示例 · 非实验数据')
  const source=JSON.parse(readFileSync(path.join(destination,'source.json'),'utf8'))
  expect(source.document.example_case.id).toBe('wb-synthetic-tutorial-v1')
  expect(source.document.synthetic).toBe(true)
  expect(source.document.rows[0].source.page_index).toBe(1)
  await page.screenshot({path:'artifacts/checkpoints/wb-example-assembly.png',fullPage:true})
 }finally{rmSync(root,{recursive:true,force:true})}
})
