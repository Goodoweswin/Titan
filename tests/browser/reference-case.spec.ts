async function openCase(page:any,mode:'annotated'|'practice'){
 const rpc=async(command:string,payload:object={})=>{const r=await(await page.request.post('/test-engine',{data:{command,payload}})).json();expect(r.ok,r.error).toBe(true);return r.data}
 const p=await rpc('reference_case',{mode});p.name+=' '+p.id
 await rpc('library_create_from_wb',{project:p});await page.reload()
 await page.getByRole('button',{name:'打开分析 '+p.name,exact:true}).click()
 if(mode==='annotated')await page.getByRole('button',{name:'目标',exact:true}).click()
}

