 await expect(page.getByLabel('IF 实验名称')).toHaveValue('history IF B')
 await rpc(page,'if_save',{project:{...a,revision:a.revision+1,fields:a.fields.filter((f:any)=>f.id!==a.fields[1].id)},expected_revision:a.saved_revision})
