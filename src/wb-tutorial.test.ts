import {describe,it,expect} from 'vitest'
import {testProject} from './test-project'
import type {AnalysisResult} from './types'
import {advanceTutorial,createTutorial,loadTutorial,saveTutorial,tutorialStepState,wbExportProof,type TutorialContext,type WbEditorState,type WbFigureState} from './wb-tutorial'

function context():TutorialContext{
 const p=testProject();p.example_case={id:'case',mode:'tutorial',source_name:'raw.tif',source_sha256:'hash',page_index:0,uint16_max_pixels:0,source_note:'teaching',suggested_window:[0,0,100,100],suggested_lane_count:1}
 p.rois=p.rois.filter(r=>r.id==='target1').map(r=>({...r,reference_id:null,band_set_id:'bands',lane_layout_id:'layout'}))
 p.lane_layouts=[{id:'layout',image_id:'im',membrane_id:'M1',window:[0,0,100,100],columns:[{lane_id:'L1',rect:[0,0,40,100]}],excluded_regions:[],source_layout_id:null,confirmed_revision:0}]
 p.band_sets=[{id:'bands',layout_id:'layout',analyte:'PROTEIN',role:'target',window:[0,0,100,100],reference_set_id:null,assignments:[{lane_id:'L1',roi_id:'target1',status:'accepted'}]}]
 const editor:WbEditorState={projectId:p.id,revision:0,imageId:'im',setId:'bands',regionEdits:0,laneSelections:0,identifications:0,selectedLane:'',hasRegion:true,hasPreview:false,unresolved:0,backgroundsReady:false,busy:false}
 return {project:p,view:'samples',active:true,editor,figure:null,result:null,exported:null}
}
function runAt(c:TutorialContext,step:number){return {...createTutorial(c.project.id),step}}
function figure(c:TutorialContext):WbFigureState{return {projectId:c.project.id,revision:0,documentId:'figure-a',version:'v1',allConfirmed:true,saved:true,ready:true}}
function result(c:TutorialContext):AnalysisResult{return {project_id:c.project.id,input_revision:0,measurements:[],normalized:[],biological:[],statistics:[],lane_results:[{membrane_id:'M1',lane_id:'L1',sample_id:'S1',analyte:'PROTEIN',band_set_id:'bands',corrected_sum:12,reference_analyte:null,reference_net:null,normalized:null,status:'blocked',flags:['missing_reference'],target_roi_id:'target1',reference_roi_id:null}]}}

describe('action-gated WB tutorial',()=>{
 it('never uses the preset rectangle as evidence of a user drawing action',()=>{
  const c=context(),r=runAt(c,1)
  expect(tutorialStepState(r,c).ready).toBe(false)
  c.editor!.regionEdits=1
  expect(tutorialStepState(r,c).ready).toBe(true)
  const moved=advanceTutorial(r,c)
  expect(moved.step).toBe(2)
  expect(c.project.revision).toBe(0)
 })
 it('requires a new lane selection after entering its step',()=>{
  const c=context(),r=runAt(c,1);c.editor!.regionEdits=1;c.editor!.laneSelections=1;c.editor!.selectedLane='L1'
  const next=advanceTutorial(r,c)
  expect(tutorialStepState(next,c).ready).toBe(false)
  c.editor!.laneSelections=2
  expect(tutorialStepState(next,c).ready).toBe(true)
 })
 it('requires resolved peaks and backgrounds without requiring manual edits',()=>{
  const c=context(),r=runAt(c,3)
  c.editor!.hasPreview=true
  expect(tutorialStepState(r,c).ready).toBe(false)
  c.editor!.identifications=1;c.editor!.unresolved=1
  expect(tutorialStepState(r,c).ready).toBe(false)
  c.editor!.unresolved=0;c.editor!.backgroundsReady=true
  expect(tutorialStepState(r,c).ready).toBe(true)
  const next=advanceTutorial(r,c)
  expect(tutorialStepState(next,c).ready).toBe(true)
  c.editor!.backgroundsReady=false
  expect(tutorialStepState(next,c).ready).toBe(false)
  expect(tutorialStepState(next,c).target).toBe('lane-correction')
  c.editor!.hasPreview=false
  expect(tutorialStepState(next,c).recovery).toBe(true)
 })
 it('rejects other-project, wrong-image, stale, busy and hidden editor state',()=>{
  const c=context(),r=runAt(c,1);c.editor!.regionEdits=1
  for(const patch of [{projectId:'other'},{revision:99},{imageId:'other'},{busy:true}]){
   expect(tutorialStepState(r,{...c,editor:{...c.editor!,...patch}}).ready).toBe(false)
  }
  expect(tutorialStepState(r,{...c,active:false}).ready).toBe(false)
  expect(tutorialStepState(r,{...c,view:'workspace'}).ready).toBe(false)
 })
 it('accepts real peak proposals already generated by adjusting a lane',()=>{
  const c=context(),r=runAt(c,3)
  c.editor!.hasPreview=true;c.editor!.identifications=1;r.baseline.identifications=1
  expect(tutorialStepState(r,c).ready).toBe(true)
 })
 it('checks real committed reviews and invalidates confirmation after undo',()=>{
  const c=context(),r=runAt(c,5)
  expect(tutorialStepState(r,c).ready).toBe(true)
  c.project.rois[0].reviewed_revision=null
  expect(tutorialStepState(r,c).ready).toBe(false)
  c.project.band_sets[0].assignments[0]={lane_id:'L1',roi_id:null,status:'pending'}
  expect(tutorialStepState(r,c).ready).toBe(false)
 })
 it('does not accept older committed measurements while new proposals remain unconfirmed',()=>{
  const c=context(),r=runAt(c,5)
  c.editor!.hasPreview=true
  expect(tutorialStepState(r,c).ready).toBe(false)
  c.editor!.hasPreview=false;c.editor!.busy=true
  expect(tutorialStepState(r,c).ready).toBe(false)
 })
 it('shows ordinary missing-reference results, but never accepts a stale result',()=>{
  const c=context(),r=runAt(c,6);c.view='results';c.result=result(c)
  expect(tutorialStepState(r,c).ready).toBe(true)
  c.result.input_revision=9
  expect(tutorialStepState(r,c).ready).toBe(false)
  c.result={...result(c),project_id:'other'}
  expect(tutorialStepState(r,c).ready).toBe(false)
 })
 it('locates the next actual figure action and requires a matching successful export',()=>{
  const c=context(),r=runAt(c,7);c.view='wb'
  expect(tutorialStepState(r,c).target).toBe('figure-new')
  c.figure={...figure(c),allConfirmed:false,saved:false,version:null}
  expect(tutorialStepState(r,c).target).toBe('figure-confirm')
  c.figure.allConfirmed=true
  expect(tutorialStepState(r,c).target).toBe('figure-save')
  c.figure=figure(c)
  expect(tutorialStepState(r,c).target).toBe('figure-export')
  expect(tutorialStepState(r,c).ready).toBe(false)
  const receipt={path:'/local/export',outputs:{'figure.png':'hash','figure.pdf':'hash','figure.svg':'hash','source.json':'hash'}}
  expect(wbExportProof(c.project,c.figure,null)).toBeNull()
  expect(wbExportProof(c.project,c.figure,{path:'/cancelled'})).toBeNull()
  c.exported=wbExportProof(c.project,c.figure,receipt)
  expect(tutorialStepState(r,c).ready).toBe(true)
  expect(advanceTutorial(r,c).status).toBe('completed')
  c.figure.documentId='other'
  expect(tutorialStepState(r,c).ready).toBe(false)
 })
 it('rejects stale or unsaved figure receipts and never advances incomplete steps',()=>{
  const c=context(),r=runAt(c,1)
  expect(advanceTutorial(r,c)).toBe(r)
  const receipt={path:'/local',outputs:{'figure.png':'h','figure.pdf':'h','figure.svg':'h','source.json':'h'}}
  expect(wbExportProof(c.project,{...figure(c),revision:8},receipt)).toBeNull()
  expect(wbExportProof(c.project,{...figure(c),saved:false},receipt)).toBeNull()
 })
})

describe('tutorial progress storage',()=>{
 const memory=()=>{const values=new Map<string,string>();return {getItem:(k:string)=>values.get(k)??null,setItem:(k:string,v:string)=>{values.set(k,v)}}}
 it('restores project-scoped step/exit state without storing scientific drafts',()=>{
  const storage=memory(),r={...createTutorial('a'),step:4,status:'dismissed' as const}
  saveTutorial(storage,r,1)
  expect(loadTutorial(storage,'a')).toMatchObject({projectId:'a',step:4,status:'dismissed'})
  expect(loadTutorial(storage,'b')).toMatchObject({projectId:'b',step:0,status:'active'})
 })
 it('bounds storage, tolerates corruption and keeps guidance usable on write failure',()=>{
  const storage=memory()
  for(let i=0;i<25;i++)saveTutorial(storage,{...createTutorial(String(i)),step:3},i)
  expect(loadTutorial(storage,'0').step).toBe(0)
  expect(loadTutorial(storage,'24').step).toBe(3)
  storage.setItem('titan-wb-tutorial-v1','{broken')
  expect(loadTutorial(storage,'24').step).toBe(0)
  expect(()=>saveTutorial({getItem:()=>null,setItem:()=>{throw Error('quota')}},createTutorial('a'))).not.toThrow()
 })
})
